"""Writes Essenthos.Corpus/Utils/UnicodeNormalization.Data.cs: the Unicode tables canonical
normalization needs, taken from Python's unicodedata.

The projects run with InvariantGlobalization, under which string.Normalize returns its input
unchanged, so NFC and NFD are computed by UnicodeNormalization from these tables instead. The
Unicode version must be Postgres's (Postgres 18 is Unicode 16.0), so that a string composed here and
one composed by normalize(..., NFC) in SQL are the same string.

    py -3.14 scripts/unicode-normalization.py
"""

import pathlib
import sys
import unicodedata

UNICODE = "16.0.0"
if unicodedata.unidata_version != UNICODE:
    sys.exit(f"This Python has Unicode {unicodedata.unidata_version}; run it with one that has {UNICODE} (py -3.14).")

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def characters():
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF or HANGUL_FIRST <= code <= HANGUL_LAST:
            continue
        yield code, chr(code)


def canonical(code):
    """The character's one-step canonical decomposition, or None when it has none."""
    mapping = unicodedata.decomposition(chr(code))
    if not mapping or mapping.startswith("<"):
        return None
    return [int(part, 16) for part in mapping.split()]


decompositions, classes, compositions = [], [], []
for code, character in characters():
    decomposed = unicodedata.normalize("NFD", character)
    if decomposed != character:
        decompositions.append(f"{code:X}=" + ".".join(f"{ord(c):X}" for c in decomposed))

    combining = unicodedata.combining(character)
    if combining:
        classes.append((code, combining))

    pair = canonical(code)
    if pair and len(pair) == 2 and unicodedata.normalize("NFC", character) == character:
        compositions.append(f"{pair[0]:X}.{pair[1]:X}={code:X}")

ranges, start = [], None
for at, (code, combining) in enumerate(classes):
    if start is None:
        start = (code, combining)
    following = classes[at + 1] if at + 1 < len(classes) else None
    if following is None or following[0] != code + 1 or following[1] != combining:
        ranges.append(f"{start[0]:X}" + ("" if start[0] == code else f"-{code:X}") + f":{combining}")
        start = None


def literal(entries):
    lines, line = [], ""
    for entry in entries:
        if len(line) + len(entry) + 1 > 100:
            lines.append(line)
            line = ""
        line += entry + ";"
    lines.append(line)
    return "\n".join(lines)


source = f"""// <auto-generated>
// Written by scripts/unicode-normalization.py from Unicode {UNICODE}; do not edit by hand.
// </auto-generated>

namespace Essenthos.Core.Utils;

internal static partial class UnicodeNormalization
{{
    /// <summary>Every character's full canonical decomposition, Hangul syllables apart: <c>code=part.part</c>, hexadecimal.</summary>
    private const string DecompositionData = \"\"\"
{literal(decompositions)}
\"\"\";

    /// <summary>The canonical combining class of every character that has one: <c>first-last:class</c>.</summary>
    private const string CombiningClassData = \"\"\"
{literal(ranges)}
\"\"\";

    /// <summary>The primary composites, by the pair they compose from: <c>first.second=composite</c>.</summary>
    private const string CompositionData = \"\"\"
{literal(compositions)}
\"\"\";
}}
"""

target = pathlib.Path(__file__).resolve().parent.parent / "Essenthos.Corpus" / "Utils" / "UnicodeNormalization.Data.cs"
target.write_text(source, encoding="utf-8", newline="\n")
print(f"{len(decompositions)} decompositions, {len(ranges)} combining-class ranges, {len(compositions)} compositions -> {target}")
