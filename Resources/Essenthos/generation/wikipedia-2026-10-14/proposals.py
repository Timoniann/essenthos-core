"""Writes review/wikipedia-proposals.json from the two agents' readings in wiki-second-read-2026-10-15.json.

Each proposal is the first reading's answer, with the lower of the two confidences, whether the
second reading agreed, and where it did not, the second reading's answer. The console shows them
beside the owner's list; nothing is decided until he answers.

    python proposals.py <essenthos-core Resources/Essenthos folder>
"""
import json
import sys
from pathlib import Path

RANK = {"low": 0, "medium": 1, "high": 2}

base = Path(sys.argv[1])
here = Path(__file__).parent
reads = json.loads((here / "wiki-second-read-2026-10-15.json").read_text(encoding="utf-8"))["entries"]


def answer(read):
    return read.get("qid") or "none"


entries = []
for entry in reads:
    first, second = entry["first"], entry["second"]
    proposal = {
        "record": entry["record"],
        "answer": answer(first),
        "confidence": min(first["confidence"], second["confidence"], key=lambda c: RANK.get(c, 0)),
        "agreed": entry["status"] == "agreed",
        "why": first.get("why"),
    }
    if not proposal["agreed"]:
        proposal["other"] = answer(second)
        proposal["otherWhy"] = second.get("why")
    entries.append(proposal)

about = (
    "What two independent agent readings (2026-10-14/15) propose for each record of wikipedia-matches.json: "
    "the item it is, or none. Generated by generation/wikipedia-2026-10-14/proposals.py; the console shows "
    "each proposal beside the entry and only the owner's answer takes effect."
)
out = base / "review" / "wikipedia-proposals.json"
out.write_text(json.dumps({"about": about, "entries": entries}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
print(len(entries), sum(e["agreed"] for e in entries))
