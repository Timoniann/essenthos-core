using Essenthos.Core.Products;

namespace Essenthos.Core.Records;

internal static partial class RecordFiles
{
    /// <summary>A canonical verse of the row, as the int[3] the engine turns into a key.</summary>
    private static string Ref(string alias) => $"ARRAY[{alias}.canonical_book, {alias}.canonical_chapter, {alias}.canonical_verse]";

    /// <summary>The columns of a canonical verse from the staged key.</summary>
    private static string Unref(string column) => $"{column}[1], {column}[2], {column}[3]";

    /// <summary>
    /// Notes of ours on a record a dataset supplied: rendered into the readers' languages, which only our own
    /// notes are. The old page hid them with the dataset's (OursOnlyRecords); the file keeps them ours.
    /// </summary>
    private const string OwnNotes = "EXISTS (SELECT 1 FROM entity_note_translation t WHERE t.entity_id = e.id)";

    /// <summary>The source texts the datasets credit their rows with: what a record of ours may not carry.</summary>
    private const string FromADataset = "(e.source LIKE 'BibleData%' OR e.source LIKE 'OpenBible%')";

    /// <summary>
    /// The new tables, and the dataset columns of a record gone (NOT-0215 point 9). Run on the database the
    /// files are loaded into, never on live (the old steps still write those columns until TSK-1449).
    /// </summary>
    private const string SchemaSql = """
        CREATE TABLE IF NOT EXISTS record_external_id (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            entity_id integer NOT NULL REFERENCES entity (id) ON DELETE CASCADE,
            dataset text NOT NULL,
            external_id text NOT NULL,
            relation text NOT NULL,
            note text);
        CREATE INDEX IF NOT EXISTS ix_record_external_id_entity_id ON record_external_id (entity_id);
        CREATE INDEX IF NOT EXISTS ix_record_external_id_dataset_external_id ON record_external_id (dataset, external_id);
        CREATE TABLE IF NOT EXISTS external_record (
            dataset text NOT NULL,
            external_id text NOT NULL,
            kind text NOT NULL,
            name text NOT NULL,
            attributes jsonb NOT NULL,
            PRIMARY KEY (dataset, external_id));
        CREATE TABLE IF NOT EXISTS external_reference (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            dataset text NOT NULL,
            external_id text,
            entity_id integer REFERENCES entity (id) ON DELETE SET NULL,
            canonical_book integer NOT NULL,
            canonical_chapter integer NOT NULL,
            canonical_verse integer NOT NULL,
            label text,
            names boolean NOT NULL,
            disputed boolean NOT NULL,
            withheld boolean NOT NULL);
        CREATE INDEX IF NOT EXISTS ix_external_reference_dataset_external_id ON external_reference (dataset, external_id);
        ALTER TABLE entity DROP COLUMN IF EXISTS source, DROP COLUMN IF EXISTS source_id, DROP COLUMN IF EXISTS open_bible_id;
        ALTER TABLE merged_record DROP COLUMN IF EXISTS record_source, DROP COLUMN IF EXISTS record_source_id;
        """;

    private static RecordFile[] Records =>
    [
        new("records/records", ProductKind.Hand,
            "slug kind subtype? place_kind? name sex? sex_source? name_gender? tribe? origin? another_name_for? byname:json?",
            """
            SELECT e.slug, e.kind, e.subtype, e.place_kind, e.name,
                   CASE WHEN q.slug IS NULL THEN e.sex ELSE q.sex END, e.sex_source, e.name_gender,
                   CASE WHEN q.slug IS NULL THEN e.tribe ELSE q.tribe END,
                   o.slug, a.slug, e.byname::text
            FROM entity e
            LEFT JOIN entity o ON o.id = e.origin_entity_id
            LEFT JOIN entity a ON a.id = e.another_name_for_entity_id
            LEFT JOIN ours_only q ON q.slug = e.slug
            ORDER BY e.slug
            """,
            """
            INSERT INTO entity (slug, kind, subtype, place_kind, name, sex, sex_source, name_gender, tribe, byname)
            SELECT slug, kind, subtype, place_kind, name, sex, sex_source, name_gender, tribe, byname FROM s ORDER BY slug
            """,
            ["entity"],
            After: """
            UPDATE entity e SET origin_entity_id = o.id FROM s JOIN entity o ON o.slug = s.origin WHERE e.slug = s.slug;
            UPDATE entity e SET another_name_for_entity_id = a.id FROM s JOIN entity a ON a.slug = s.another_name_for WHERE e.slug = s.slug;
            DO $$ BEGIN
              IF (SELECT count(*) FROM s WHERE origin IS NOT NULL) <> (SELECT count(*) FROM entity WHERE origin_entity_id IS NOT NULL)
                 OR (SELECT count(*) FROM s WHERE another_name_for IS NOT NULL) <> (SELECT count(*) FROM entity WHERE another_name_for_entity_id IS NOT NULL)
              THEN RAISE EXCEPTION 'records/records: an origin or another_name_for names no record'; END IF;
            END $$;
            """,
            ExportLoaded: """
            SELECT e.slug, e.kind, e.subtype, e.place_kind, e.name, e.sex, e.sex_source, e.name_gender, e.tribe,
                   o.slug, a.slug, e.byname::text
            FROM entity e
            LEFT JOIN entity o ON o.id = e.origin_entity_id
            LEFT JOIN entity a ON a.id = e.another_name_for_entity_id
            ORDER BY e.slug
            """,
            About: "Our records. No dataset source: where a record came from is its claims; a dataset's id for it is in records/external-ids."),

        new("records/i18n/eng/records", ProductKind.Hand,
            "slug line? notes? modern?",
            $"""
            SELECT * FROM (
                SELECT e.slug, CASE WHEN q.slug IS NULL THEN e.distinguisher ELSE q.line END line,
                       CASE WHEN q.slug IS NULL OR {OwnNotes} THEN e.notes END notes, e.modern_equivalent modern
                FROM entity e LEFT JOIN ours_only q ON q.slug = e.slug) x
            WHERE line IS NOT NULL OR notes IS NOT NULL OR modern IS NOT NULL
            ORDER BY slug
            """,
            """
            UPDATE entity e SET distinguisher = s.line, notes = s.notes, modern_equivalent = s.modern FROM s WHERE e.slug = s.slug
            """,
            [],
            ExportLoaded: """
            SELECT e.slug, e.distinguisher, e.notes, e.modern_equivalent FROM entity e
            WHERE e.distinguisher IS NOT NULL OR e.notes IS NOT NULL OR e.modern_equivalent IS NOT NULL
            ORDER BY e.slug
            """,
            About: "A record's line under the name, its notes and what the place is today, in English."),

        new("records/external-ids", ProductKind.Hand,
            "slug dataset external_id relation note?",
            """
            SELECT * FROM (
                SELECT e.slug, 'bibledata', e.source_id, 'same-as', NULL::text FROM entity e WHERE e.source_id ~ '^(person|place):'
                UNION ALL
                SELECT e.slug, 'openbible', e.open_bible_id, 'same-as', NULL FROM entity e WHERE e.open_bible_id IS NOT NULL
                UNION ALL
                SELECT e.slug,
                       CASE WHEN m.record_source_id LIKE 'openbible:%' THEN 'openbible' ELSE 'bibledata' END,
                       CASE WHEN m.record_source_id LIKE 'openbible:%' THEN substr(m.record_source_id, 11) ELSE m.record_source_id END,
                       'folded', 'the id of ' || m.slug || ', folded into this record'
                FROM merged_record m JOIN entity e ON e.id = m.entity_id
                WHERE m.record_source_id ~ '^(person|place|openbible):') x
            ORDER BY 1, 2, 3, 4
            """,
            """
            INSERT INTO record_external_id (entity_id, dataset, external_id, relation, note)
            SELECT e.id, s.dataset, s.external_id, s.relation, s.note FROM s JOIN entity e ON e.slug = s.slug
            ORDER BY s.slug, s.dataset, s.external_id, s.relation
            """,
            ["record_external_id"],
            ExportLoaded: """
            SELECT e.slug, x.dataset, x.external_id, x.relation, x.note
            FROM record_external_id x JOIN entity e ON e.id = x.entity_id ORDER BY 1, 2, 3, 4
            """,
            About: "The ids the datasets give our records. The only place a dataset's id of a record lives; a dataset never makes a record."),

        new("records/claims", ProductKind.Hand,
            "slug method confidence? by note?",
            $"""
            SELECT * FROM (
                SELECT e.slug, c.method, c.confidence::text, c.source, c.note
                FROM entity_claim c JOIN entity e ON e.id = c.entity_id
                UNION ALL
                SELECT e.slug, 'manual', NULL, 'Essenthos, a record ' || split_part(e.source, ' by ', 1) || ' supplied as '
                       || coalesce(e.open_bible_id, e.source_id) || ', kept as ours by the rework of 2026-11', NULL
                FROM entity e WHERE {FromADataset}) x
            ORDER BY 1, 4, 2, 3, 5
            """,
            """
            INSERT INTO entity_claim (entity_id, method, confidence, source, note)
            SELECT e.id, s.method, s.confidence::double precision, s.by, s.note FROM s JOIN entity e ON e.slug = s.slug
            ORDER BY s.slug, s.by, s.method, s.confidence, s.note
            """,
            ["entity_claim"],
            ExportLoaded: """
            SELECT e.slug, c.method, c.confidence::text, c.source, c.note
            FROM entity_claim c JOIN entity e ON e.id = c.entity_id ORDER BY 1, 4, 2, 3, 5
            """,
            About: "Why each record exists, and who said so."),

        new("records/names", ProductKind.Hand,
            "slug n:int label kind? hebrew? hebrew_transliterated? greek? greek_transliterated? hebrew_strong? greek_strong? aspect_of? by?",
            """
            SELECT e.slug, row_number() OVER (PARTITION BY n.entity_id ORDER BY n.id), n.label, n.kind, n.hebrew,
                   n.hebrew_transliterated, n.greek, n.greek_transliterated, n.hebrew_strong_number, n.greek_strong_number,
                   a.slug, n.source
            FROM entity_name n JOIN entity e ON e.id = n.entity_id LEFT JOIN entity a ON a.id = n.aspect_of_entity_id
            ORDER BY 1, 2
            """,
            """
            INSERT INTO entity_name (entity_id, label, kind, hebrew, hebrew_transliterated, greek, greek_transliterated,
                                     hebrew_strong_number, greek_strong_number, aspect_of_entity_id, source)
            SELECT e.id, s.label, s.kind, s.hebrew, s.hebrew_transliterated, s.greek, s.greek_transliterated,
                   s.hebrew_strong, s.greek_strong, a.id, s.by
            FROM s JOIN entity e ON e.slug = s.slug LEFT JOIN entity a ON a.slug = s.aspect_of
            WHERE s.aspect_of IS NULL OR a.id IS NOT NULL
            ORDER BY s.slug, s.n
            """,
            ["entity_name"],
            About: "The names a record bears, in its order (n). Their meanings are in i18n/eng/names."),

        new("records/i18n/eng/names", ProductKind.Hand,
            "slug n:int meaning",
            """
            SELECT * FROM (
                SELECT e.slug, row_number() OVER (PARTITION BY n.entity_id ORDER BY n.id) n, n.meaning
                FROM entity_name n JOIN entity e ON e.id = n.entity_id) x
            WHERE meaning IS NOT NULL ORDER BY 1, 2
            """,
            """
            UPDATE entity_name t SET meaning = s.meaning
            FROM s, (SELECT n.id, e.slug, row_number() OVER (PARTITION BY n.entity_id ORDER BY n.id) n
                     FROM entity_name n JOIN entity e ON e.id = n.entity_id) k
            WHERE k.id = t.id AND k.slug = s.slug AND k.n = s.n
            """,
            []),

        new("records/alternatives", ProductKind.Hand,
            "slug n:int alternative? describes? back:bool by",
            """
            SELECT e.slug, row_number() OVER (PARTITION BY x.entity_id ORDER BY x.id), a.slug, x.describes, x.back, x.source
            FROM entity_alternative x JOIN entity e ON e.id = x.entity_id LEFT JOIN entity a ON a.id = x.alternative_entity_id
            ORDER BY 1, 2
            """,
            """
            INSERT INTO entity_alternative (entity_id, alternative_entity_id, describes, reason, back, source)
            SELECT e.id, a.id, s.describes, '', s.back, s.by
            FROM s JOIN entity e ON e.slug = s.slug LEFT JOIN entity a ON a.slug = s.alternative
            WHERE s.alternative IS NULL OR a.id IS NOT NULL
            ORDER BY s.slug, s.n
            """,
            ["entity_alternative"],
            About: "Who else a record may be. The reason, in English, is in i18n/eng/alternatives."),

        new("records/i18n/eng/alternatives", ProductKind.Hand,
            "slug n:int reason",
            """
            SELECT e.slug, row_number() OVER (PARTITION BY x.entity_id ORDER BY x.id), x.reason
            FROM entity_alternative x JOIN entity e ON e.id = x.entity_id ORDER BY 1, 2
            """,
            """
            UPDATE entity_alternative t SET reason = s.reason
            FROM s, (SELECT x.id, e.slug, row_number() OVER (PARTITION BY x.entity_id ORDER BY x.id) n
                     FROM entity_alternative x JOIN entity e ON e.id = x.entity_id) k
            WHERE k.id = t.id AND k.slug = s.slug AND k.n = s.n
            """,
            []),

        new("records/folds", ProductKind.Hand,
            "slug folded_into name distinguisher? method confidence? by reason",
            """
            SELECT m.slug, e.slug, m.name, m.distinguisher, m.method, m.confidence::text, m.source, m.reason
            FROM merged_record m JOIN entity e ON e.id = m.entity_id ORDER BY 1
            """,
            """
            INSERT INTO merged_record (slug, entity_id, name, distinguisher, method, confidence, source, reason)
            SELECT s.slug, e.id, s.name, s.distinguisher, s.method, s.confidence::double precision, s.by, s.reason
            FROM s JOIN entity e ON e.slug = s.folded_into ORDER BY s.slug
            """,
            ["merged_record"],
            About: "Old addresses of records folded into another; each redirects to the record it was folded into."),
    ];
