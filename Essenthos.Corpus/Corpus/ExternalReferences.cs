namespace Essenthos.Core.Corpus;

/// <summary>
/// The verses a dataset lists for its records, kept apart from the verses a reader is shown
/// (<c>entity_verse</c>): BibleData's, which a reader is not shown (<see cref="ShownVerses"/>) and
/// whose labels still say which name each verse calls a person by, and the gazetteer's. The record
/// files load the table (<c>external/*/references</c>); it is not a table of the model, so it has no
/// migration, and a database the files never filled has it from <see cref="Schema"/>.
/// </summary>
internal static class ExternalReferences
{
    public const string Table = "external_reference";

    /// <summary>BibleData's id in the table's <c>dataset</c> column.</summary>
    public const string BibleData = "bibledata";

    public const string Schema = """
        CREATE TABLE IF NOT EXISTS external_reference (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            dataset text NOT NULL,
            external_id text,
            entity_id integer REFERENCES entity (id) ON DELETE SET NULL,
            canonical_book integer NOT NULL,
            canonical_chapter integer NOT NULL,
            canonical_verse integer NOT NULL,
            label text,
            names boolean NOT NULL,
            disputed boolean NOT NULL,
            withheld boolean NOT NULL);
        CREATE INDEX IF NOT EXISTS ix_external_reference_dataset_external_id ON external_reference (dataset, external_id);
        CREATE INDEX IF NOT EXISTS ix_external_reference_entity_id ON external_reference (entity_id);
        """;
}
